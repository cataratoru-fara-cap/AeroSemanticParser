# -- helpers -------------------------------------------------------------------
def fmt(n) -> str:
    return f"{int(round(n)):,}"


def pct(a, b, digits=1) -> str:
    return f"{100 * a / b:.{digits}f}" if b else "0"


def short(n) -> str:
    n = float(n)
    if n >= 1e6:
        return f"{n / 1e6:.1f}M".replace(".0M", "M")
    if n >= 1e3:
        return f"{n / 1e3:.0f}k"
    return str(int(n))


def esc(s) -> str:
    s = str(s)
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"),
                 ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"),
                 ("^", r"\textasciicircum{}")):
        s = s.replace(a, b)
    return s


def write(name: str, body: str) -> None:
    (GEN / name).write_text("% generated by scripts/figures.py — do not edit\n" + body, encoding="utf-8")


