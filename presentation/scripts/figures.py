def hbars(rows: list[tuple[str, float, str]], color: str, width=".8\\linewidth", height=None,
          xmax_pad=1.28) -> str:
    """Horizontal bars, one series, value labels at the bar ends. rows: (label, value, shown)."""
    h = height or f"{max(len(rows), 2) * 0.78 + 0.4:.2f}cm"
    labels = ",".join("{" + lab + "}" for lab, _, _ in rows)
    coords = " ".join(f"({v},{{{lab}}}) [{shown}]" for lab, v, shown in rows)
    xmax = max(v for _, v, _ in rows) * xmax_pad
    return (
        "\\begin{tikzpicture}\n\\begin{axis}[gm hbar, scale only axis, width=" + width + ", height=" + h
        + ", xmax=" + f"{xmax:.0f}" + ", symbolic y coords={" + labels + "},\n"
        "  point meta=explicit symbolic, nodes near coords={\\pgfplotspointmeta}]\n"
        f"\\addplot[fill={color}] coordinates {{{coords}}};\n"
        "\\end{axis}\n\\end{tikzpicture}\n")


